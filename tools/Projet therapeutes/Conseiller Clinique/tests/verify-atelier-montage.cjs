const { chromium } = require('playwright');
const { strict: assert } = require('node:assert');
const { readFileSync } = require('node:fs');
const { join } = require('node:path');

(async () => {
  const browser = await chromium.launch({ channel: 'chrome' });
  try {
    const page = await browser.newPage({ acceptDownloads: true });
    const errors = [];
    page.on('pageerror', e => errors.push(e.stack || e.message));
    await page.goto('file://' + join(__dirname, '../atelier-diapos.html'));
    await page.evaluate(async () => {
      const images = [];
      for (const color of ['#a52a2a', '#204c91']) {
        const canvas = document.createElement('canvas'); canvas.width = 640; canvas.height = 360;
        const ctx = canvas.getContext('2d'); ctx.fillStyle = color; ctx.fillRect(0,0,640,360);
        images.push({ blob: await new Promise(resolve => canvas.toBlob(resolve, 'image/jpeg')) });
      }
      window.__chutier = { dernier: () => ({ res: { images } }) };
      document.getElementById('cv-mp4').disabled = false;
      document.getElementById('cv-duree').value = '2';
    });
    const mp3 = join(__dirname, 'atelier-test-tone.mp3');
    await page.locator('#am-add-voice').setInputFiles(mp3);
    await page.waitForFunction(() => document.querySelectorAll('[data-source-lane="voice"] [data-source]').length === 1);
    await page.locator('#am-add-music').setInputFiles([mp3,mp3]);
    await page.waitForFunction(() => document.querySelectorAll('[data-source-lane="music"] [data-source]').length === 2);
    assert.equal(await page.locator('[data-clip]').count(), 0, 'importer conserve le son en bibliothèque');
    await page.locator('[data-source-lane="voice"] [data-source] span').first().dragTo(page.locator('[data-master-lane="voice"]'));
    await page.locator('[data-source-lane="music"] [data-source] span').first().dragTo(page.locator('[data-master-lane="music"]'));
    await page.locator('[data-source-lane="music"] [data-source] span').last().dragTo(page.locator('[data-master-lane="music"]'));
    await page.waitForFunction(() => document.querySelectorAll('[data-clip]').length === 3);
    assert.equal(await page.locator('#am-vignettes-details').getAttribute('open'), null, 'vignettes repliées');
    if (process.env.ATELIER_SCREENSHOT) await page.locator('#am-workbench').screenshot({path:process.env.ATELIER_SCREENSHOT});
    assert.equal(await page.locator('.am-lane').count(), 3);
    assert.equal(await page.locator('[data-master-lane="voice"] [data-clip]').count(), 1);
    assert.equal(await page.locator('[data-master-lane="music"] [data-clip]').count(), 2);
    await page.locator('[data-clip="2"]').click();
    await page.locator('[data-field="db"][data-track="2"]').fill('-24');
    await page.locator('[data-field="db"][data-track="2"]').dispatchEvent('change');
    assert.equal(await page.locator('[data-field="db"][data-track="2"]').inputValue(), '-24');
    await page.locator('[data-master-db="music"]').fill('-9');
    assert.equal(await page.locator('#am-music-db').innerText(), '-9 dB');
    await page.locator('#am-play').click();
    await page.evaluate(() => { window.__liveGainCalls = 0; const p = AudioParam.prototype, original = p.setTargetAtTime; p.setTargetAtTime = function (...args) { window.__liveGainCalls++; return original.apply(this,args); }; });
    await page.locator('[data-master-db="music"]').fill('-12');
    assert.ok(await page.evaluate(() => window.__liveGainCalls) > 0, 'volume modifié pendant la lecture');
    await page.locator('#am-seek').fill('2.2');
    await page.waitForFunction(() => document.querySelector('#am-play').textContent === 'Pause');
    assert.match(await page.locator('#am-clock').innerText(), /00:02 \/ 00:04/, 'scrubbing resynchronise image et audio');
    await page.waitForFunction(() => {
      const pixel=document.querySelector('#am-preview').getContext('2d').getImageData(480,270,1,1).data;
      return pixel[2] > pixel[0];
    });
    await page.locator('#am-stop').click();
    await page.locator('[data-master-lane="voice"] [data-clip="0"]').click();
    await page.locator('[data-field="at"][data-track="0"]').fill('0');
    await page.locator('[data-field="at"][data-track="0"]').dispatchEvent('change');
    await page.locator('#am-seek').fill('0.5');
    await page.locator('#am-split').click();
    assert.equal(await page.locator('[data-clip]').count(), 4);
    await page.locator('#am-seek').fill('0.75');
    await page.locator('#am-add-point').click();
    assert.equal(await page.locator('.am-automation circle').count(), 3);
    await page.locator('[data-master-mute="music"]').click();
    assert.equal(await page.locator('[data-master-mute="music"]').innerText(), 'Réactiver');
    await page.locator('[data-master-mute="music"]').click();
    await page.locator('#am-play').click();
    await page.waitForTimeout(250);
    assert.match(await page.locator('#am-clock').innerText(), /00:00 \/ 00:04/);
    await page.locator('#am-stop').click();
    const downloadPromise = page.waitForEvent('download', {timeout:15000});
    await page.locator('#am-export').click();
    const download = await downloadPromise.catch(async e => { console.error('STATUT EXPORT', await page.locator('#am-status').innerText()); throw e; });
    const bytes = readFileSync(await download.path());
    assert.ok(bytes.includes(Buffer.from('soun')), 'le MP4 doit contenir une piste sonore');
    assert.ok(bytes.includes(Buffer.from('mp4a')), 'le MP4 doit contenir de l’audio AAC');
    const info = await page.evaluate(async encoded => {
      const bytes = Uint8Array.from(atob(encoded), c => c.charCodeAt(0));
      const video = document.createElement('video');
      video.src = URL.createObjectURL(new Blob([bytes], {type:'video/mp4'}));
      await new Promise((resolve, reject) => { video.onloadedmetadata=resolve; video.onerror=reject; });
      return {width:video.videoWidth,height:video.videoHeight,duration:video.duration};
    }, bytes.toString('base64'));
    assert.equal(info.width,1920); assert.equal(info.height,1080);
    assert.ok(info.duration > 3.5 && info.duration < 4.6);
    const movedClip = await page.locator('[data-master-lane="music"] [data-clip]').last().getAttribute('data-clip');
    await page.locator(`[data-master-lane="music"] [data-clip="${movedClip}"] .am-clip-label`).dragTo(page.locator('[data-master-lane="voice"]'));
    assert.equal(await page.locator('[data-master-lane="voice"] [data-clip]').count(), 3);
    await page.locator(`[data-master-lane="voice"] [data-clip="${movedClip}"] .am-clip-label`).dragTo(page.locator('[data-master-lane="music"]'));
    assert.equal(await page.locator('[data-master-lane="music"] [data-clip]').count(), 2);
    const beforeRemove=await page.locator('[data-clip]').count();
    await page.locator(`[data-clip="${movedClip}"] [data-clip-remove]`).click();
    assert.equal(await page.locator('[data-clip]').count(),beforeRemove-1);
    await page.locator('[data-source-lane="voice"] [data-source-action="cut"]').click();
    assert.equal(await page.locator('[data-source-lane="voice"] [data-source]').count(),2);
    await page.locator('[data-source-lane="voice"] [data-source-action="copy"]').first().click();
    await page.locator('[data-source-lane="voice"] [data-source-action="paste"]').click();
    assert.equal(await page.locator('[data-source-lane="voice"] [data-source]').count(),3);
    await page.evaluate(encoded => {
      const bytes=Uint8Array.from(atob(encoded),c=>c.charCodeAt(0));
      const transfer=new DataTransfer();transfer.items.add(new File([bytes],'glisse-depose.mp3',{type:'audio/mpeg'}));
      const lane=document.querySelector('[data-import-lane="music"]');
      lane.dispatchEvent(new DragEvent('dragover',{bubbles:true,cancelable:true,dataTransfer:transfer}));
      lane.dispatchEvent(new DragEvent('drop',{bubbles:true,cancelable:true,dataTransfer:transfer}));
    },readFileSync(mp3).toString('base64'));
    await page.waitForFunction(() => document.querySelectorAll('[data-source-lane="music"] [data-source]').length === 3);
    assert.deepEqual(errors, []);
    console.log('PASS Atelier montage : deux pistes Master, coupe, point de volume, sourdine, mixage AAC dans MP4, 1920 × 1080, '+info.duration+' s');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
